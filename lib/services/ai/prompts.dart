## المصدر (source)
- الجهة التي صدر عنها الخبر كما تظهر في المواد (مثل: وزارة الصحة، مديرية الصحة لولاية عنابة، المنظمة العالمية للصحة). إذا لم تظهر الجهة بوضوح فاتركه فارغاً ولا تخمّن.

## quotes_intro و quotes (في التصريحات فقط، وإلا فاتركهما فارغين)
- لا تنقل الكلام المنطوق حرفياً كما هو. اتبع هذه المراحل:
  1. افهم لغة كل كلمة في الكلام (دارجة جزائرية، فصحى، فرنسية، أمازيغية، إنجليزية...)، لأن الكلمات الأجنبية قد تُسمع خطأً كأنها عربية.
  2. كوّن في ذهنك النص الكامل لما قاله المتحدث، واحذف منه التردد والتلعثم والهمهمة («إمم»، «آآ»...) وكلمات الحشو والتكرار وزلات اللسان والجمل المبتورة التي تراجع عنها.
  3. استخرج أهم التصريحات بطريقة عقلانية، وأعد صياغة كل منها على لسان المتحدث (بصيغة المتكلم: «خضعت...»، «ليس لدي...»، «يجب أن نثمّن...») في جملة كاملة واضحة، دون إضافة أي معنى أو رقم لم يقله، ودون تغيير موقفه أو نبرته.
- quotes: قائمة التصريحات المعاد صياغتها، كل تصريح عنصر مستقل يحمل فكرة واحدة، دون الرمز 🔴 ودون علامات تنصيص.
- quotes_intro: جملة تقديم واحدة تنتهي بنقطتين «:»، فيها صفة المتحدث ثم اسمه كهاشتاغ (الكلمات موصولة بشرطة سفلية) ثم ما يتحدث عنه. مثال على الشكل فقط: «المتحدث الرسمي #اسم_المتحدث يكشف عن القرار الجديد ويتحدث عن أسبابه:». إذا لم يُعرف الاسم فاستعمل الصفة وحدها.
- مثال على شكل quotes (للأسلوب فقط):
