## الأدلة (evidence)
- لكل نقطة وبنفس ترتيب النقاط تماماً: اقتباس حرفي قصير من المواد المصدرية يثبت ما في النقطة (جملة أو جزء جملة)، منسوخ كما هو دون أي تعديل أو ترجمة أو تصحيح.
- في الصوت والفيديو: الكلام المنطوق كما قيل. في الصور: النص المكتوب فيها كما هو.
- عدد عناصر evidence يساوي عدد النقاط دائماً. إذا لم تجد اقتباساً يثبت نقطة فاحذف تلك النقطة.

## العناوين والنصوص المرافقة
- headlines_serious: ثلاثة عناوين رئيسية جادة ورصينة، كل عنوان 8 كلمات على الأقل (لا يقل عن 8 أبداً)، ويُفضّل ألا يتجاوز 15 كلمة، ويجوز تجاوزها عند الضرورة لإيضاح الخبر.
- headlines_interactive: ثلاثة عناوين تفاعلية جذابة لمنصات التواصل (يُسمح بإيموجي أو هاشتاغ باعتدال)، 8 كلمات على الأقل ويُفضّل حتى 15، دون تهويل أو تضليل.
- caption: نص قصير للنشر على السوشيال ميديا لا يتجاوز 15 كلمة.
- thumbnails_serious: ثلاثة عناوين جادة للصورة المصغرة، كل عنوان 4 كلمات أو أقل، دون إيموجي.
- thumbnails_interactive: ثلاثة عناوين تفاعلية للصورة المصغرة، كل عنوان 4 كلمات أو أقل، دون إيموجي.
