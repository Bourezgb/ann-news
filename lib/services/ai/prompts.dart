  static String request({required NewsCategory category, required StatementStyle style, required bool weAreSource}) {
    final b = StringBuffer()
      ..writeln('صنّف المحرر هذه المادة على أنها: «${category.label}».')
      ..writeln('اكتب كل المخرجات بالعربية الفصحى.');
    if (category.isStatement) {
      b
        ..writeln()
        ..writeln('هذه المادة تصريح لشخصية ما:')
        ..writeln(
          '- speaker_name و speaker_role: اسم المتحدث وصفته/مهنته فقط إذا ذُكرا صراحة في المواد (مكتوبين أو منطوقين)، وإلا فاتركهما فارغين ولا تخمّن.',
        )
        ..writeln('- لا تكتب نقطة للتعريف بالمتحدث؛ التطبيق يضيفها تلقائياً.')
        ..writeln('- النقاط تقتصر حصراً على عناصر التصريح والأفكار التي تناولها المتحدث، كل فكرة في نقطة.')
        ..writeln(
          '- صُغ النقاط بصيغة نقل التصريح لا بصيغة الخبر: كل نقطة تُنسب للمتحدث صراحة '
          '(مثل: «الوزير أكد أن ...»، «المتحدث أوضح أن ...»، «الوزير شدد على ...») وتتضمن كلامه بين « » كلما أمكن.',
        )
        ..writeln(
          '- quotes_intro و quotes: اتبع قواعد إعادة الصياغة على لسان المتحدث المذكورة في التعليمات '
          '(فهم لغة كل كلمة، حذف التردد والأخطاء، استخراج التصريحات بعقلانية).',
        )
        ..writeln('- العناوين تعبّر عن مضمون التصريح.');
      b.writeln(
        style == StatementStyle.dialect
            ? '- quotes: أعد الصياغة بلهجة المتحدث نفسها لكن نظيفة ومفهومة (دون تردد أو أخطاء).'
            : '- quotes: أعد الصياغة بالعربية الفصحى السليمة على لسان المتحدث.',
      );
      if (style == StatementStyle.dialect) {
        b.writeln(
          '- انقل كلام المتحدث المباشر بين علامتي التنصيص « » حرفياً بنفس اللهجة المنطوقة التي تحدث بها (مثلاً الدارجة الجزائرية) دون تفصيحه أو تعديله. ما هو خارج علامتي التنصيص يُكتب بالفصحى.',
        );
      } else {
        b.writeln(
          '- انقل كلام المتحدث بالعربية الفصحى بين علامتي التنصيص « » مع الحفاظ الدقيق على المعنى دون زيادة أو نقصان.',
        );
      }
    } else {
      b.writeln('هذه مادة خبرية وليست تصريحاً: اترك speaker_name و speaker_role و quotes_intro و quotes فارغة.');
    }
    if (category.isVideoCover) {
      b.writeln(
        'المادة موجهة لفيديو ${category == NewsCategory.reel ? 'ريل (Reels)' : 'يوتيوب'}: '
        'عنوان الصورة المصغرة سيُكتب على غلاف الفيديو، فاجعله قوياً ومختصراً وصحيحاً تماماً.',
      );
    }
    if (weAreSource) {
      b.writeln('مصدر الخبر هو الشبكة الجزائرية للأخبار نفسها: اترك source فارغاً.');
    }
    b
      ..writeln()
      ..writeln('المواد المصدرية:');
    return b.toString();
  }

